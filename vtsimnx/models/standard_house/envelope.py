def room_nodes(
    room_volume: Mapping[str, float] | None = None,
    t_capa_per_m3: float = T_CAPA_PER_M3,
    m_capa_per_m3: float = M_CAPA_PER_M3,
) -> list[dict[str, Any]]:
    """室内ノードだけを返す。外部・地盤の境界温度は呼び出し側で足す。"""
    if room_volume is None:
        room_volume = ROOM_VOLUME
    nodes: list[dict[str, Any]] = []
    for key, vol in room_volume.items():
        nodes.append({
            "key": key,
            "calc_t": True,
            "calc_x": True,
            "v": vol,
            "thermal_mass": vol * t_capa_per_m3,
            "moisture_capacity": vol * m_capa_per_m3,
            "moisture_capacity_unit": "J/(kg/kg')",
        })
    return nodes


def bind_surface_types(
    types: Mapping[str, Mapping[str, Any]],
    layers: Mapping[str, Any],
    solar: Mapping[str, Any] | None = None,
    nocturnal: Mapping[str, Any] | None = None,
) -> dict[str, dict[str, Any]]:
    """部位カタログに層と、用意済みの日射・夜間放射系列を載せる。"""
    bound: dict[str, dict[str, Any]] = {}
    for name, spec in types.items():
        item = {k: v for k, v in spec.items() if k not in {"layer_key", "solar_key", "nocturnal_key"}}
        layer_key = spec.get("layer_key")
        if layer_key is not None:
            item["layers"] = layers[layer_key]
        solar_key = spec.get("solar_key")
        if solar_key is not None:
            if solar is None:
                raise ValueError(f"surface {name!r} needs solar[{solar_key!r}]")
            item["solar"] = solar[solar_key]
        nocturnal_key = spec.get("nocturnal_key")
        if nocturnal_key is not None:
            if nocturnal is None:
                raise ValueError(f"surface {name!r} needs nocturnal[{nocturnal_key!r}]")
            item["nocturnal"] = nocturnal[nocturnal_key]
        bound[name] = item
    return bound


def compose_surfaces(
    rows: list[Mapping[str, Any]],
    catalog: Mapping[str, Mapping[str, Any]],
) -> list[dict[str, Any]]:
    """接続行と部位カタログを surfaces リストにする。"""
    return [{"key": row["key"], **catalog[row["surface"]], "area": row["area"]} for row in rows]
